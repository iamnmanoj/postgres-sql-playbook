#!/usr/bin/env python3
"""Build KEYWORD_INDEX.md and GLOSSARY.md from the chapter files, and validate query IDs.

* KEYWORD_INDEX.md: every query (Q-id, title, keywords) per chapter, plus a keyword → query-id lookup.
* GLOSSARY.md: every row of every chapter README "Keywords & functions" table, merged A–Z,
  plus a hand-written list of core concepts.
* Fails (exit 1) on duplicate IDs, out-of-sequence IDs, or queries without a Keywords line.

Run:  python3 scripts/build_index.py
"""
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CHAPTERS = sorted(p for p in (ROOT / "chapters").iterdir() if p.is_dir())

HEADER_RE = re.compile(r"^-- \[(Q|E)(\d{2})\.(\d{2})\] (.+)$")
KEYWORDS_RE = re.compile(r"^-- Keywords: (.+)$")
SECTION_RE = re.compile(r"^-- SECTION: (.+)$")


def chapter_title(ch: Path) -> str:
    readme = ch / "README.md"
    if readme.exists():
        first = readme.read_text(encoding="utf-8").splitlines()[0]
        return first.lstrip("# ").strip()
    return ch.name


def parse_sql(path: Path, kind: str):
    """Yield dicts with id, title, keywords, section for headers of the given kind (Q or E)."""
    items, section, current = [], None, None
    for line in path.read_text(encoding="utf-8").splitlines():
        if m := SECTION_RE.match(line):
            section = m.group(1).strip()
        elif (m := HEADER_RE.match(line)) and m.group(1) == kind:
            current = {"id": f"{kind}{m.group(2)}.{m.group(3)}", "chapter": m.group(2),
                       "seq": int(m.group(3)), "title": m.group(4).strip(),
                       "keywords": [], "section": section}
            items.append(current)
        elif current is not None and (m := KEYWORDS_RE.match(line)) and not current["keywords"]:
            current["keywords"] = [k.strip() for k in m.group(1).split(",") if k.strip()]
    return items


def split_keyword_cell(cell: str):
    # "`a`, `b`" -> ["a", "b"];  plain text kept as-is
    ticks = re.findall(r"`([^`]+)`", cell)
    return ticks if ticks else [cell.strip()]


def main() -> int:
    errors, all_queries, glossary = [], [], defaultdict(list)
    seen_ids = set()
    exercise_total = 0

    for ch in CHAPTERS:
        num = ch.name[:2]
        q = ch / "queries.sql"
        if q.exists():
            items = parse_sql(q, "Q")
            for i, it in enumerate(items, start=1):
                if it["id"] in seen_ids:
                    errors.append(f"duplicate id {it['id']}")
                seen_ids.add(it["id"])
                if it["chapter"] != num:
                    errors.append(f"{it['id']} found in chapter {num}")
                if it["seq"] != i:
                    errors.append(f"{ch.name}: expected Q{num}.{i:02d} but found {it['id']}")
                if not it["keywords"]:
                    errors.append(f"{it['id']} has no Keywords line")
                it["dir"] = ch.name
            all_queries.extend(items)
        ex, sol = ch / "exercises.sql", ch / "solutions.sql"
        if ex.exists() and sol.exists():
            ex_ids = [i["id"] for i in parse_sql(ex, "E")]
            sol_ids = [i["id"] for i in parse_sql(sol, "E")]
            exercise_total += len(ex_ids)
            if ex_ids != sol_ids:
                errors.append(f"{ch.name}: exercises {ex_ids} != solutions {sol_ids}")

        readme = ch / "README.md"
        if readme.exists():
            in_table = False
            for line in readme.read_text(encoding="utf-8").splitlines():
                if line.startswith("## Keywords"):
                    in_table = True
                    continue
                if in_table and line.startswith("## "):
                    break
                if in_table and line.startswith("|") and not line.startswith("|---") and "What it does" not in line:
                    cells = [c.strip() for c in re.split(r"(?<!\\)\|", line.strip())[1:-1]]
                    if len(cells) >= 3:
                        for kw in split_keyword_cell(cells[0]):
                            glossary[kw.replace("\\|", "|")].append((cells[1].replace("\\|", "|"), ch.name, cells[2]))

    if errors:
        print("\n".join(errors))
        return 1

    # ---------------- KEYWORD_INDEX.md ----------------
    out = ["# Keyword index", "",
           "Generated by `scripts/build_index.py` from the `-- [Qnn.mm]` / `-- Keywords:` headers in every `queries.sql`.",
           f"**{len(all_queries)} unique queries** across {len({q['dir'] for q in all_queries})} chapters, plus "
           f"**{exercise_total} exercises** with solutions.", "",
           "- [Queries by chapter](#queries-by-chapter)", "- [Keyword → queries](#keyword--queries)", "",
           "## Queries by chapter", ""]
    by_chapter = defaultdict(list)
    for q in all_queries:
        by_chapter[q["dir"]].append(q)
    for d in sorted(by_chapter):
        out.append(f"### [{chapter_title(ROOT / 'chapters' / d)}](chapters/{d}/README.md)")
        out.append("")
        out.append("| ID | Query | Category | Keywords |")
        out.append("|---|---|---|---|")
        for q in by_chapter[d]:
            kws = ", ".join(f"`{k}`" for k in q["keywords"]).replace("|", "\\|")
            out.append(f"| [{q['id']}](chapters/{d}/queries.sql) | {q['title'].replace('|', '\\|')} | {q['section'] or ''} | {kws} |")
        out.append("")
    out += ["## Keyword → queries", "", "| Keyword | Queries |", "|---|---|"]
    kw_map = defaultdict(list)
    for q in all_queries:
        for k in q["keywords"]:
            kw_map[k].append(q["id"])
    for k in sorted(kw_map, key=lambda s: (s.lstrip("\\@#-&|<>~!?%:").lower(), s)):
        out.append(f"| `{k.replace('|', '\\|')}` | {', '.join(kw_map[k])} |")
    (ROOT / "KEYWORD_INDEX.md").write_text("\n".join(out) + "\n", encoding="utf-8")

    # ---------------- GLOSSARY.md ----------------
    g = ["# Glossary", "",
         "Generated by `scripts/build_index.py` from the *Keywords & functions* table of every chapter README.",
         "Core concepts first, then every keyword/function A–Z with the chapter that teaches it.", "",
         (ROOT / "scripts" / "glossary_concepts.fragment").read_text(encoding="utf-8").strip(), "",
         "## Keywords & functions A–Z", ""]
    current_letter = None
    def letter_of(s):
        first = (re.sub(r"^[^A-Za-z0-9]+", "", s)[:1] or "#").upper()
        return first if first.isalpha() else "#"

    def sort_key(s):
        return (letter_of(s) != "#", letter_of(s), re.sub(r"^[^A-Za-z0-9]+", "", s).lower(), s)

    for kw in sorted(glossary, key=sort_key):
        letter = letter_of(kw)
        if letter != current_letter:
            g += ["", f"### {letter}", "", "| Keyword / function | Meaning | Where |", "|---|---|---|"]
            current_letter = letter
        meaning, ch_dir, ids = glossary[kw][0]
        where = "; ".join(f"[ch {c[:2]}](chapters/{c}/README.md) {i}" for _, c, i in glossary[kw])
        g.append(f"| `{kw.replace('|', '\\|')}` | {meaning.replace('|', '\\|')} | {where} |")
    (ROOT / "GLOSSARY.md").write_text("\n".join(g) + "\n", encoding="utf-8")

    print(f"OK: {len(all_queries)} queries, {exercise_total} exercises, {len(kw_map)} distinct query keywords, "
          f"{len(glossary)} glossary entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
